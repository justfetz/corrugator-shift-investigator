#!/usr/bin/env python3
"""Write evals/client_money.json: the client formula's figures for one shift (issue #31b).

The card re-prices a dollar in the browser (src/investigator/web/money.js) from the quantities a tool returned at
the server's rates. This file holds one such case: get_shift_dollars for shift 2 on 2026-09-14 at the post's rates
(`input`, the quantities the card holds) and what money.js makes of it at other rates (`output`). Three checks hold
the loop shut:

- evals/make_value_goldens.py turns `output` into the value case value-dollars-shift-0914-shift-2-client, so
  evals/run.py holds the server's own get_shift_dollars at those rates to the client's figures, field for field;
- tests/test_ui.cjs holds money.js to `output` from `input`, so a change to the client formula shows;
- tests/test_money_ui.py holds `input` to the tool as it runs now, so a change to the tool shows.

Needs node (it runs tests/money_cli.cjs). Run it after an intended change to the cost model or the client formula,
then python3 evals/make_value_goldens.py.
"""
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'evals' / 'client_money.json'
DAY, SHIFT, RATES = '2026-09-14', 2, 'paper:60,hour:1350.5,margin:35,trim:3.1'
DROP = ('source_ids',)


GOLDEN_AS_OF = '2026-09-30'   # the golden window (evals/run.py GOLDEN_AS_OF, tests/conftest.py), not the rolling year ending yesterday


def tool_input():
    """get_shift_dollars at the post's rates, as the card holds it (record ids and the SQL trace left out)."""
    os.environ.pop('INVESTIGATOR_RATES', None)
    os.environ['INVESTIGATOR_AS_OF'] = GOLDEN_AS_OF   # before the store is imported: the tests read this window
    os.environ.pop('INVESTIGATOR_PREBUILT', None)
    sys.path.insert(0, str(ROOT / 'src'))
    from investigator import cost_model
    from investigator.agent import Agent
    from investigator.record_store import default_store
    analysis = default_store().day_analysis(DAY)
    data = Agent(analysis)._execute('get_shift_dollars', {'shift': SHIFT}, {}, cost_model.effective())
    data = {k: v for k, v in data.items() if k != 'trace'}
    data['rows'] = [{k: v for k, v in row.items() if k not in DROP} for row in data['rows']]
    return json.loads(json.dumps(data)), cost_model.client_config()


def main():
    data, cfg = tool_input()
    with tempfile.NamedTemporaryFile('w', suffix='.json', delete=False) as f:
        json.dump({'cfg': cfg, 'tool': 'get_shift_dollars', 'data': data, 'rates': RATES}, f)
    try:
        out = json.loads(subprocess.run(['node', str(ROOT / 'tests' / 'money_cli.cjs'), 'reprice', f.name],
                                        check=True, capture_output=True, text=True).stdout)
    finally:
        os.unlink(f.name)
    keep = ('gap', 'rank', 'paper_usd', 'machine_time_usd', 'usd', 'usd_per_year', 'msf_not_made', 'contribution_usd',
            'contribution_usd_per_year', 'contribution_status', 'usd_basis', 'share_of_window_pct')
    totals = ('total_usd', 'total_paper_usd', 'total_machine_time_usd', 'total_usd_per_year', 'total_contribution_usd',
              'contribution_status', 'provenance',
              # what the card states under the headline and in its arithmetic block (the #31b review: the server's, not the browser's)
              'buckets', 'area_sqft', 'area_msf', 'stop_minutes', 'speed_minutes', 'waste_run_minutes', 'machine_minutes', 'msf_not_made',
              'trim_pct_of_gross', 'trim_target_pct', 'trim_points_over', 'trim_over_usd', 'trim_over_usd_per_year', 'trim_over_basis')
    doc = {'about': __doc__.strip().splitlines()[0] + ' GENERATED by evals/make_client_money.py; do not edit by hand.',
           'day': DAY, 'shift': SHIFT, 'rates': RATES, 'cfg': cfg, 'input': data,
           'output': {'rows': [{k: r[k] for k in keep} for r in out['rows']], **{k: out[k] for k in totals}}}
    OUT.write_text(json.dumps(doc, indent=1) + '\n')
    print(f'wrote {OUT.relative_to(ROOT)}: {len(out["rows"])} rows at {RATES}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
