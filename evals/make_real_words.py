"""Write src/investigator/real_words.py: the English words the typo rule must never turn into a measure (issue #105).

    pip install wordfreq            # a generator-only dependency, not the application's
    python3 evals/make_real_words.py

A word goes in when it is everyday English (wordfreq's Zipf frequency 1.5 or more, about one use in thirty
million words) and `agent.nearest_measure` would otherwise read it as a measure: "throughout" as throughput,
"qualify" as quality, "steps" as stops. Run it again after a change to the measure
vocabulary or the edit rule; tests/test_question_scope.py fails when the committed list is out of step with
the rule. Words left out on purpose are the issue's own typos that happen to be archaic English ("wast", as
in "thou wast"): nobody asks a corrugator question in it.
"""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'src'))

from investigator.agent import nearest_measure  # noqa: E402

MIN_ZIPF = 1.5
TYPOS_NOT_WORDS = {'wast'}   # archaic English, and one of the issue's typos


def real_words():
    from wordfreq import iter_wordlist, zipf_frequency
    words = set()
    for word in iter_wordlist('en'):
        if zipf_frequency(word, 'en') < MIN_ZIPF:
            break   # the list is in frequency order
        if word.isalpha() and word.isascii() and word == word.lower() and word not in TYPOS_NOT_WORDS and nearest_measure(word):
            words.add(word)
    return sorted(words)


def main():
    words = real_words()
    lines = ['"""English words one edit from a measure word, which the typo rule leaves alone (issue #105).',
             '',
             f'Generated by evals/make_real_words.py from wordfreq (Zipf frequency {MIN_ZIPF:g} or more); do not edit by hand."""',
             'REAL_WORDS = frozenset((']
    row = '   '
    for word in words:
        item = f" '{word}',"
        if len(row) + len(item) > 116:
            lines.append(row)
            row = '   '
        row += item
    lines += [row, '))', '']
    (ROOT / 'src' / 'investigator' / 'real_words.py').write_text('\n'.join(lines))
    print(f'{len(words)} words')


if __name__ == '__main__':
    main()
